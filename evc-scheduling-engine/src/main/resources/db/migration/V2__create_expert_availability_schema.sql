-- Flyway Migration V2: Create Expert Availability Schema

CREATE TABLE expert_availabilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expert_id BIGINT NOT NULL,
    available_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_availabilities_expert FOREIGN KEY (expert_id) REFERENCES experts (id) ON DELETE CASCADE,
    CONSTRAINT uk_expert_available_date UNIQUE (expert_id, available_date)
);

CREATE INDEX idx_availabilities_expert ON expert_availabilities (expert_id);
CREATE INDEX idx_availabilities_date ON expert_availabilities (available_date);
CREATE INDEX idx_availabilities_expert_date ON expert_availabilities (expert_id, available_date);

