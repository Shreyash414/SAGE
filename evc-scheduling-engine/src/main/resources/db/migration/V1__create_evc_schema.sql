CREATE TABLE institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aicte_id VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    region VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_institutions_aicte_id UNIQUE (aicte_id)
);

CREATE TABLE experts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150),
    discipline VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE evc_inspections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL,
    duration_in_days INTEGER NOT NULL,
    required_member_count INTEGER NOT NULL,
    earliest_start_date DATE NOT NULL,
    latest_start_date DATE NOT NULL,
    scheduled_start_date DATE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_inspections_institution FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT chk_inspections_duration CHECK (duration_in_days > 0),
    CONSTRAINT chk_inspections_member_count CHECK (required_member_count > 0),
    CONSTRAINT chk_inspections_date_window CHECK (earliest_start_date <= latest_start_date),
    CONSTRAINT chk_inspections_status CHECK (status IN ('PENDING', 'SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE committee_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id BIGINT NOT NULL,
    expert_id BIGINT NOT NULL,
    role VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_assignments_inspection FOREIGN KEY (inspection_id) REFERENCES evc_inspections (id) ON DELETE CASCADE,
    CONSTRAINT fk_assignments_expert FOREIGN KEY (expert_id) REFERENCES experts (id) ON DELETE RESTRICT,
    CONSTRAINT uk_assignment_inspection_expert UNIQUE (inspection_id, expert_id),
    CONSTRAINT chk_assignments_role CHECK (role IN ('CHAIRPERSON', 'MEMBER', 'SPECIALIST')),
    CONSTRAINT chk_assignments_status CHECK (status IN ('PROPOSED', 'CONFIRMED', 'DECLINED'))
);

CREATE INDEX idx_inspections_institution ON evc_inspections (institution_id);
CREATE INDEX idx_inspections_status ON evc_inspections (status);
CREATE INDEX idx_assignments_inspection ON committee_assignments (inspection_id);
CREATE INDEX idx_assignments_expert ON committee_assignments (expert_id);
